const express = require("express");
const router = express.Router();
const { pool } = require("../db");
const crypto = require("crypto");
const fs = require("fs");

/**
 * Anyone scanning a report card's QR code hits this route. It re-derives
 * the HMAC signature server-side and looks the record up fresh in the
 * database — it never trusts anything beyond the token's identifiers, so
 * a photocopied or edited PDF cannot be made to "verify" as genuine.
 */
router.get("/:token", async (req, res) => {
  try {
    const decoded = Buffer.from(req.params.token, "base64url").toString("utf8");
    const parts = decoded.split(".");

    if (parts[0] === "T") {
      // Terminal report token: T.studentId.term.academicYear.sig
      const [, studentId, term, academicYear, sig] = parts;
      const payload = `T.${studentId}.${term}.${academicYear}`;
      const expected = crypto.createHmac("sha256", process.env.QR_SIGNING_SECRET).update(payload).digest("hex").slice(0, 24);
      if (sig !== expected) return res.status(400).json({ valid: false, reason: "Signature mismatch." });

      const { rows } = await pool.query(
        `SELECT tr.content_hash, tr.generated_at, tr.class, tr.term, tr.academic_year, tr.aggregate_total, tr.subjects_included, s.full_name
         FROM terminal_reports tr JOIN students s ON s.id = tr.student_id
         WHERE tr.student_id = $1 AND tr.term = $2 AND tr.academic_year = $3`,
        [studentId, term, academicYear]
      );
      if (!rows[0]) return res.status(404).json({ valid: false, reason: "No matching official record." });
      return res.json({ valid: true, record: rows[0] });
    }

    // Per-subject report card token: examId.version.studentId.sig
    const [examId, version, studentId, sig] = parts;
    const payload = `${examId}.${version}.${studentId}`;
    const expected = crypto.createHmac("sha256", process.env.QR_SIGNING_SECRET).update(payload).digest("hex").slice(0, 24);
    if (sig !== expected) return res.status(400).json({ valid: false, reason: "Signature mismatch." });

    const { rows } = await pool.query(
      `SELECT rc.content_hash, rc.generated_at, e.class, e.subject, e.term, e.academic_year, s.full_name,
              em.score, em.grade
       FROM report_cards rc
       JOIN exams e ON e.id = rc.exam_id
       JOIN students s ON s.id = rc.student_id
       JOIN exam_marks em ON em.exam_id = rc.exam_id AND em.version = rc.version AND em.student_id = rc.student_id
       WHERE rc.exam_id = $1 AND rc.version = $2 AND rc.student_id = $3`,
      [examId, version, studentId]
    );
    if (!rows[0]) return res.status(404).json({ valid: false, reason: "No matching official record." });

    res.json({ valid: true, record: rows[0] });
  } catch {
    res.status(400).json({ valid: false, reason: "Malformed verification token." });
  }
});

// Serves the actual PDF the QR code represents. Public and unauthenticated
// by design — the same as walking up to a printed noticeboard — but it
// still re-validates the signature first, so a tampered or guessed token
// can't pull back a real file.
router.get("/:token/pdf", async (req, res) => {
  try {
    const decoded = Buffer.from(req.params.token, "base64url").toString("utf8");
    const parts = decoded.split(".");

    if (parts[0] === "T") {
      const [, studentId, term, academicYear, sig] = parts;
      const payload = `T.${studentId}.${term}.${academicYear}`;
      const expected = crypto.createHmac("sha256", process.env.QR_SIGNING_SECRET).update(payload).digest("hex").slice(0, 24);
      if (sig !== expected) return res.status(400).send("Invalid verification link.");

      const { rows } = await pool.query(
        `SELECT file_path FROM terminal_reports WHERE student_id = $1 AND term = $2 AND academic_year = $3`,
        [studentId, term, academicYear]
      );
      if (!rows[0]) return res.status(404).send("No matching terminal report found.");
      if (!fs.existsSync(rows[0].file_path)) {
        return res.status(410).send("This report's file is no longer available on the server. It may need to be regenerated by the school.");
      }
      res.setHeader("Content-Type", "application/pdf");
      return fs.createReadStream(rows[0].file_path).pipe(res);
    }

    const [examId, version, studentId, sig] = parts;
    const payload = `${examId}.${version}.${studentId}`;
    const expected = crypto.createHmac("sha256", process.env.QR_SIGNING_SECRET).update(payload).digest("hex").slice(0, 24);
    if (sig !== expected) return res.status(400).send("Invalid verification link.");

    const { rows } = await pool.query(
      `SELECT file_path FROM report_cards WHERE exam_id = $1 AND version = $2 AND student_id = $3`,
      [examId, version, studentId]
    );
    if (!rows[0]) return res.status(404).send("No matching report card found.");
    if (!fs.existsSync(rows[0].file_path)) {
      return res.status(410).send("This report card's file is no longer available on the server. It may need to be regenerated by the school.");
    }

    res.setHeader("Content-Type", "application/pdf");
    fs.createReadStream(rows[0].file_path).pipe(res);
  } catch {
    res.status(400).send("Malformed verification link.");
  }
});

module.exports = { router };
